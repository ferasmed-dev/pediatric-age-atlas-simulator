let current = 'es';
export function setLang(l) { current = STRINGS[l] ? l : 'es'; }
export function getLang() { return current; }

/** Look up a dotted key and fill {params}. */
export function t(key, params) {
  let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS[current]);
  if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS.es);
  if (v == null) return key;
  if (typeof v !== 'string') return v;
  return params ? v.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m)) : v;
}

/** Number formatting by language. */
export function fmt(x, digits = 0) {
  if (x == null || !Number.isFinite(x)) return '—';
  return new Intl.NumberFormat(current === 'en' ? 'en-GB' : 'es-ES', { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(x);
}
